#include "algo_top.h"

// 256x256 图像
#define IMG_W 256
#define IMG_H 256
#define FRAME_SIZE (IMG_W * IMG_H)

// Gaussian kernel
#define CORNER_WEIGHT   1
#define NEIGHBOR_WEIGHT 2
#define SELF_WEIGHT     4

// 3x3 Gaussian:
//
// 1 2 1
// 2 4 2
// 1 2 1
//
// sum = 16

// ------------------------------------------------------------
// 流控制
//
// idx:
//   当前输入 pixel 在这一帧中的 index
//
// op_idx:
//   当前应该输出的 pixel index
//
// q:
//   保存最近 515 个有效输入 pixel
//
// 由于：
//   当前输入 i
//   输出 i - 257
//
// 所以需要保存：
//
// i-514  i-513  i-512
// i-258  i-257  i-256
// i-2    i-1    i
//
// 一共 515 个 pixel。
// ------------------------------------------------------------

int idx = 0;
int op_idx = 0;

int first_frame = 1;
int flushing = 0;

int q[515] = {0};


void denoise(
    ap8_t in_data,
    int in_valid,
    int in_last,

    ap8_t* out_data,
    int* out_last,
    int* out_valid
)
{
    // --------------------------------------------------------
    // 默认输出
    // --------------------------------------------------------

    *out_data  = 0;
    *out_valid = 0;
    *out_last  = 0;


    // ========================================================
    // 第一部分：
    // 正常接收输入，同时输出延迟 257 个 pixel 的结果
    // ========================================================

    if (in_valid) {

        // ----------------------------------------------------
        // 1. 把当前输入放入 515 深度循环队列
        // ----------------------------------------------------

        q[idx % 515] = in_data;


        // ----------------------------------------------------
        // 2. 从第 257 个输入开始产生输出
        //
        // idx = 257
        // 输出 pixel 0
        //
        // idx = 258
        // 输出 pixel 1
        //
        // ...
        // ----------------------------------------------------

        if (idx >= 257) {

            if (op_idx == idx - 257) {

                // =================================================
                // 当前真正要输出的是：
                //
                // center = idx - 257
                //
                // =================================================

                int center = idx - 257;

                // 当前 pixel 在图像中的列
                int col = center % IMG_W;

                // 当前 pixel 在图像中的行
                int row = center / IMG_W;


                // -------------------------------------------------
                // 边界 pixel：
                //
                // 前两行
                // 前两列
                //
                // 没有完整 3x3 window
                // 直接输出原始 pixel
                // -------------------------------------------------

                if (row < 2 || col < 2) {

                    *out_data =
                        q[center % 515];

                }

                // -------------------------------------------------
                // 内部 pixel：
                //
                // 有完整 3x3 Gaussian window
                // -------------------------------------------------

                else {

                    int sum =
                          q[(idx - 514) % 515] * CORNER_WEIGHT
                        + q[(idx - 513) % 515] * NEIGHBOR_WEIGHT
                        + q[(idx - 512) % 515] * CORNER_WEIGHT

                        + q[(idx - 258) % 515] * NEIGHBOR_WEIGHT
                        + q[(idx - 257) % 515] * SELF_WEIGHT
                        + q[(idx - 256) % 515] * NEIGHBOR_WEIGHT

                        + q[(idx - 2) % 515] * CORNER_WEIGHT
                        + q[(idx - 1) % 515] * NEIGHBOR_WEIGHT
                        + q[idx % 515] * CORNER_WEIGHT;

                    // Gaussian kernel 权重总和 = 16
                    *out_data = (ap8_t)(sum >> 4);
                }


                *out_valid = 1;

                op_idx++;
            }
        }


        // ----------------------------------------------------
        // 当前输入是不是这一帧最后一个 pixel
        // ----------------------------------------------------

        if (in_last) {

            /*
             * 当前 idx = 65535
             *
             * 本拍仍然正常输出 pixel 65278。
             *
             * 下一拍开始 flush：
             *
             * 65279
             * 65280
             * ...
             * 65535
             *
             * 一共 257 个 pixel。
             */

            idx = 0;

            flushing = 1;

        }
        else {

            idx++;
        }
    }


    // ========================================================
    // 第二部分：
    // 当前一帧输入结束以后，把最后 257 个 pixel 冲出来
    // ========================================================

    if (flushing && !in_valid) {

        // ----------------------------------------------------
        // op_idx 此时应该是：
        //
        // 65279
        //
        // ----------------------------------------------------

        if (op_idx < FRAME_SIZE) {

            *out_data =
                q[op_idx % 515];

            *out_valid = 1;


            // 最后一个 pixel
            if (op_idx == FRAME_SIZE - 1) {

                *out_last = 1;

                flushing = 0;

                // 为下一帧重新开始
                op_idx = 0;

            }
            else {

                op_idx++;
            }
        }
    }


    // ========================================================
    // 第一帧结束之前：
    //
    // op_idx 还是从 0 开始。
    // 第二帧开始以后，不再需要 first_frame。
    //
    // 这里保留变量，只是为了和你原来的结构一致。
    // ========================================================

    first_frame = 0;
}